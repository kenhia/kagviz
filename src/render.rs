//! The static report: facts in, one self-contained HTML file out.
//!
//! Renders from [`Summary`] alone — never from the transcript — so the
//! extractor/renderer seam stays honest and `kagviz show <id> --json` output
//! is a valid input. Nothing here computes a number; if a value is not already
//! in the facts, it does not appear on the page.
//!
//! Self-contained is a hard requirement, not a preference: no external fonts,
//! stylesheets, scripts or images, so the file still renders correctly with no
//! network in five years, and can be mailed or archived as one artifact.

use crate::fmt;
use crate::label;
use crate::summary::{ActivitySpan, Bucket, Involvement, Phase, Summary};
use chrono::{DateTime, SecondsFormat, Utc};
use std::collections::BTreeMap;

/// Render the whole report.
pub fn report(s: &Summary) -> String {
    let mut h = String::with_capacity(32 * 1024);
    h.push_str("<!doctype html>\n<html lang=\"en\">\n<head>\n");
    h.push_str("<meta charset=\"utf-8\">\n");
    h.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
    h.push_str(&format!("<title>{}</title>\n", esc(&title(s))));
    h.push_str("<style>\n");
    h.push_str(CSS);
    h.push_str("</style>\n</head>\n<body>\n<main>\n");

    header(&mut h, s);
    if s.skipped_lines > 0 {
        h.push_str(&format!(
            "<p class=\"warn\">{} transcript line(s) did not parse. Every number below is \
             a partial reading.</p>\n",
            s.skipped_lines
        ));
    }
    written(&mut h, s);
    headline(&mut h, s);
    time_strip(&mut h, s);
    phases_section(&mut h, s);
    // Three siblings, not a nested column: the grid decides how many fit, so
    // a wide screen gets three across instead of one card and a lot of nothing.
    h.push_str("<div class=\"cols\">\n");
    tool_mix(&mut h, s);
    file_changes(&mut h, s);
    tokens(&mut h, s);
    h.push_str("</div>\n");
    involvement(&mut h, s);
    delegation(&mut h, s);

    h.push_str("<footer>Generated by kagviz. ");
    // The old footer said "nothing here is inferred", which stops being true
    // the moment a headline is on the page. It has to say which parts are
    // which rather than keep a claim that is now half wrong.
    match &s.labels {
        Some(l) => h.push_str(&format!(
            "Every <em>figure</em> is computed from the transcript. The text marked \
             <em>written</em> — the headline and the phase labels — was written by {} \
             over those figures, and is the only thing here that was not measured. ",
            esc(&label::attribution(l)),
        )),
        None => {
            h.push_str("Every figure is computed from the transcript; nothing here is inferred. ")
        }
    }
    h.push_str("Times are UTC.</footer>\n");
    h.push_str("</main>\n</body>\n</html>\n");
    h
}

fn title(s: &Summary) -> String {
    let project = s.project.as_deref().unwrap_or("session");
    match &s.started {
        Some(t) => format!("{project} — {}", t.format("%Y-%m-%d")),
        None => project.to_string(),
    }
}

fn header(h: &mut String, s: &Summary) {
    h.push_str("<header>\n");
    h.push_str(&format!("<h1>{}</h1>\n", esc(&title(s))));
    h.push_str("<dl class=\"meta\">\n");
    meta(h, "session", s.session_id.as_deref().unwrap_or_default());
    meta(h, "cwd", s.cwd.as_deref().unwrap_or_default());
    meta(h, "branch", s.git_branch.as_deref().unwrap_or_default());
    meta(h, "cli", join(s.cli_versions.iter().cloned()));
    meta(h, "models", join(s.models.keys().cloned()));
    meta(
        h,
        "window",
        match (&s.started, &s.ended) {
            (Some(a), Some(b)) => format!("{} → {}", stamp(a), stamp(b)),
            _ => String::new(),
        },
    );
    h.push_str("</dl>\n</header>\n");
}

/// The model-written headline — the only prose on this page nobody counted.
///
/// It sits above the numbers because that is where a reader starts, and it is
/// styled so it can never be mistaken for one of them: no `.stat` card, no
/// large numeral, an accent rule down the side, and an attribution naming the
/// model in the block itself rather than only in the footer. A reader who
/// cannot tell the sentence from the counts has been handed exactly the
/// confusion this project exists to avoid.
///
/// Absent when there are no labels — which is the default path, so the page
/// below has to look finished without it, not broken.
fn written(h: &mut String, s: &Summary) {
    let Some(l) = &s.labels else {
        return;
    };
    h.push_str("<section class=\"written\">\n");
    h.push_str(&format!("<p class=\"said\">{}</p>\n", esc(&l.headline)));
    h.push_str(&format!(
        "<p class=\"by\"><span class=\"mark\">written</span> by {} over the facts below. \
         It and the marked phase labels are the only text here that was not \
         measured.</p>\n",
        esc(&label::attribution(l)),
    ));
    h.push_str("</section>\n");
}

/// The four numbers that answer "how did this go" at a glance.
///
/// Active time is the headline and wall clock is its sub-label rather than its
/// peer. Both have to be on the page — active alone is dishonest about a
/// session resumed over three days, which is why `transcript-format.md` trap #2
/// exists — but equal billing put the eye on the bigger, less meaningful
/// number. Wall reads as the context for active, which is what it is.
fn headline(h: &mut String, s: &Summary) {
    let failures = s.total_tool_failures();
    h.push_str("<section class=\"stats\">\n");
    stat(
        h,
        "active",
        &fmt::duration(s.active_secs),
        &format!(
            "over {} wall · {} idle",
            fmt::duration(s.wall_secs),
            fmt::duration(s.idle_secs)
        ),
    );
    if let Some(dominant) = s.dominant_phase() {
        stat(
            h,
            "phases",
            &s.phases.len().to_string(),
            &format!("mostly {}", dominant.label()),
        );
    }
    stat(
        h,
        "turns",
        &s.assistant_turns.to_string(),
        &format!("{} user prompt(s)", s.user_prompts),
    );
    // The count says nothing without its denominator beside it — 45 failed of
    // 2,777 is a different session from 45 of 90 — so the rate follows it on
    // the same line. `tool_failure_rate` owns the denominator decision and
    // the `<unknown>` guard; the zero case stays bare.
    let failed = match (failures, s.tool_failure_rate()) {
        (0, _) => "none failed".to_string(),
        (n, Some(rate)) => format!("{n} failed · {}", fmt::percent(rate)),
        (n, None) => format!("{n} failed"),
    };
    // Delegated calls are named right here rather than only in the tier
    // below. A session that spawned three agents shows three `Agent` calls in
    // this number, and a reader who stops at the headline should still learn
    // that most of the work happened somewhere else.
    let delegated = s.delegation.totals.tool_calls.values().sum::<u32>();
    let note = if delegated > 0 {
        format!("{failed} · {} more delegated", delegated)
    } else {
        failed
    };
    stat(h, "tools", &s.total_tool_calls().to_string(), &note);
    h.push_str("</section>\n");
}

/// The time strip: uniformly-scaled buckets, with idle collapsed to a labelled
/// break rather than stretched across the page.
fn time_strip(h: &mut String, s: &Summary) {
    let a = &s.activity;
    if a.spans.is_empty() {
        return;
    }
    let peak = a.peak_records().max(1);
    let marks = marks_by_bucket(s);

    h.push_str("<section class=\"card\">\n<h2>Time</h2>\n");
    h.push_str(&format!(
        "<p class=\"note\">{} of work in {} stretch(es), {} per column. Idle gaps of \
         {}+ are collapsed to a break.</p>\n",
        fmt::duration(s.active_secs),
        a.spans.len(),
        fmt::duration(a.bucket_secs),
        fmt::duration(crate::summary::IDLE_GAP_SECS),
    ));
    // The band above the columns names its phase in words only where there is
    // room for the word. On a session with hundreds of stretches there never
    // is, so say plainly what carries the kind instead — otherwise a reader
    // meets a row of colours with no key on the card they are looking at.
    if !s.phases.is_empty() {
        h.push_str(
            "<p class=\"note\">Band colours name the phase kind — the Phases card below \
             is the key, and every band names itself on hover.</p>\n",
        );
    }
    // Break labels need room to sit in; past a dozen stretches there is none,
    // and the durations live in the tooltips instead.
    let roomy = a.spans.len() <= LABELLED_BREAKS_MAX;
    // ...and past sixty, the fixed-width breaks themselves start eating the
    // strip. On the corpus's 209-span session, 208 breaks at 6px each claimed
    // 1248px while the work columns were squeezed onto their 2px floor: the
    // panel that exists to collapse idle was rendering 72% idle. A break only
    // has to be *visible*, not proportional — its duration is deliberately not
    // to scale — so above this many it narrows and gives the width back.
    let class = match a.spans.len() {
        n if n <= LABELLED_BREAKS_MAX => "roomy",
        n if n <= NARROW_BREAKS_MIN => "dense",
        _ => "packed",
    };
    // Past a few hundred columns no CSS constant reaches the strip: it is a
    // wall of 2px bars, and the fix is a zoom (#1591 — the real one lands in
    // the front-end). Until then, a checkbox: CSS `:checked` alone, no
    // script, so the report stays self-contained. Checked, every column takes
    // a fixed readable width and the strip scrolls sideways. It only ever
    // widens, so below the threshold it would change nothing and is not
    // offered — the control precedes the strip as its *sibling*, which is the
    // whole mechanism (`~`), so it cannot live inside a `<p>`.
    let buckets: usize = a.spans.iter().map(|sp| sp.buckets.len()).sum();
    if buckets >= ZOOM_MIN_BUCKETS {
        h.push_str(
            "<input type=\"checkbox\" id=\"zoom\" class=\"zoom\">\
             <label class=\"zoomctl\" for=\"zoom\">zoom in<span> — every column at a \
             readable width; the strip scrolls sideways</span></label>\n",
        );
    }
    h.push_str(&format!("<div class=\"strip {class}\">\n"));

    for (si, span) in a.spans.iter().enumerate() {
        if span.idle_before_secs > 0 {
            let label = fmt::duration(span.idle_before_secs);
            h.push_str(&format!(
                "<div class=\"gap\" title=\"{} idle\">",
                esc(&label)
            ));
            if roomy {
                h.push_str(&format!("<span>{}</span>", esc(&label)));
            }
            h.push_str("</div>\n");
        }
        h.push_str(&format!(
            "<div class=\"span\" style=\"flex-grow:{}\">\n",
            span.buckets.len()
        ));
        phase_bands(h, s, si, span);
        h.push_str("<div class=\"cols-b\">\n");
        for (bi, bucket) in span.buckets.iter().enumerate() {
            let at = span.started + chrono::Duration::seconds(bi as i64 * a.bucket_secs);
            let mark = marks.get(&(si, bi));
            column(h, bucket, peak, &at, mark);
        }
        h.push_str("</div>\n<div class=\"axis\">");
        h.push_str(&format!(
            "<span>{}</span><span>{}</span>",
            esc(&clock(&span.started)),
            esc(&fmt::duration(span.secs))
        ));
        h.push_str("</div>\n</div>\n");
    }

    h.push_str("</div>\n");
    h.push_str(
        "<p class=\"legend\"><span class=\"key bar\"></span>work \
         <span class=\"key barfail\"></span>tool failure \
         <span class=\"key mkuser\"></span>user prompt \
         <span class=\"key mkask\"></span>question asked \
         <span class=\"key gapkey\"></span>idle, collapsed</p>\n",
    );
    h.push_str("</section>\n");
}

/// Above this many stretches of work there is no room to label the breaks.
const LABELLED_BREAKS_MAX: usize = 12;
/// Above this many, the breaks narrow so the work columns keep the width.
/// Sixty 6px breaks is about 350px — a quarter of a typical strip, and the
/// most idle should ever take on a panel whose job is collapsing it.
///
/// Narrowing further is not the answer, and this is the place someone would
/// try it. Past a few hundred stretches the breaks are noise however thin they
/// are, and that is the same density at which the whole strip stops being
/// legible — the fix there is zooming it (#1591), not shaving pixels here.
const NARROW_BREAKS_MIN: usize = 60;

/// Columns at or above which the strip offers the zoom-in checkbox.
///
/// The zoom sets each column to [`ZOOM_COLUMN_PX`]; at the layout's full
/// width — 1480px less the page and card padding, about 1,400px of strip —
/// that is room for roughly 116 columns before the flex share squeezes them
/// narrower. Below that count the zoom would change nothing at full width,
/// and a control that does nothing is worse than one that arrives a little
/// late on a half-width window. Ken's goldilocks reference (img-639 on
/// #1591) is a 118-column strip filling exactly that width, which is where
/// the number comes from. Across the corpus it offers the box on about
/// 250 of 400 sessions: `MAX_BUCKETS` is 240, so anything over an hour or two
/// saturates the strip.
const ZOOM_MIN_BUCKETS: usize = 120;

/// Column width, in CSS pixels, that the zoom sets — the density of the
/// reference snip (11–12px). Spelled in the `.zoom:checked` rule in [`CSS`]
/// and mirrored here for the doc comment; the zoom test holds the two in step.
#[allow(
    dead_code,
    reason = "read by that test; the stylesheet is the real use"
)]
const ZOOM_COLUMN_PX: u32 = 12;

/// The band width, in CSS pixels, at which a phase label is worth drawing.
///
/// Sized for the *longest* label — `implementing`, twelve characters at 9.5px
/// plus its padding — so a label that is shown is never a clipped one. A
/// narrower band keeps its colour and its tooltip, and loses only the
/// fragment that was unreadable anyway.
///
/// Unlike the two above, this one cannot be applied here: a band's width is
/// not a fact about the session, it is what the browser works out from the
/// flex share, the window and the 2px column floor. The number is therefore
/// spelled in the `@container` rule in [`CSS`] and mirrored here for the doc
/// comment; `a_band_too_narrow_for_its_label_shows_colour_and_tooltip_instead`
/// holds the two in step.
#[allow(
    dead_code,
    reason = "read by that test; the stylesheet is the real use"
)]
const BAND_LABEL_MIN_PX: u32 = 64;

/// The phase band over one span's columns.
///
/// A bucket belongs to whichever phase was running when it opened. At a wide
/// bucket width several phases can fall inside one column and only the first
/// gets drawn — [`phases_section`] reports how many that cost, because a
/// silently dropped phase would read as a phase that never happened.
fn phase_bands(h: &mut String, s: &Summary, si: usize, span: &ActivitySpan) {
    let runs = bands_for_span(s, si, span);
    if runs.is_empty() {
        return;
    }
    h.push_str("<div class=\"bands\">");
    for (pi, columns) in runs {
        let p = &s.phases[pi];
        h.push_str(&format!(
            "<div class=\"band ph-{}\" style=\"flex-grow:{columns}\" title=\"{}\">\
             <span>{}</span></div>",
            p.kind.label(),
            esc(&phase_tip(p)),
            esc(p.kind.label()),
        ));
    }
    h.push_str("</div>\n");
}

/// Runs of `(phase index, columns)` covering a span's buckets, left to right.
fn bands_for_span(s: &Summary, si: usize, span: &ActivitySpan) -> Vec<(usize, usize)> {
    let width = s.activity.bucket_secs.max(1);
    let here: Vec<usize> = (0..s.phases.len())
        .filter(|&i| s.phases[i].span == si)
        .collect();
    if here.is_empty() {
        return Vec::new();
    }
    let mut runs: Vec<(usize, usize)> = Vec::new();
    let mut cur = 0;
    for bi in 0..span.buckets.len() {
        let at = span.started + chrono::Duration::seconds(bi as i64 * width);
        while cur + 1 < here.len() && s.phases[here[cur + 1]].started <= at {
            cur += 1;
        }
        match runs.last_mut() {
            Some((last, columns)) if *last == here[cur] => *columns += 1,
            _ => runs.push((here[cur], 1)),
        }
    }
    runs
}

/// How many phases the strip could not give a column of its own.
fn phases_without_a_band(s: &Summary) -> usize {
    let drawn: usize = s
        .activity
        .spans
        .iter()
        .enumerate()
        .map(|(si, span)| bands_for_span(s, si, span).len())
        .sum();
    s.phases.len().saturating_sub(drawn)
}

fn phase_tip(p: &Phase) -> String {
    let mut tip = format!(
        "{} · {} · {}",
        p.kind.label(),
        clock(&p.started),
        fmt::duration(p.secs)
    );
    if p.tool_calls > 0 {
        tip.push_str(&format!(" · {} tool call(s)", p.tool_calls));
    }
    if p.tool_failures > 0 {
        tip.push_str(&format!(", {} failed", p.tool_failures));
    }
    if let Some(opened) = &p.opened_by {
        tip.push_str(" — ");
        tip.push_str(&label_of(opened));
    }
    tip
}

fn mix_line(p: &Phase) -> String {
    p.mix
        .parts()
        .iter()
        .map(|(name, n)| format!("{name} {n}"))
        .collect::<Vec<_>>()
        .join(" · ")
}

/// Past this many phases the ordered list stops being readable and the
/// longest ones are shown instead. The count that was dropped is always said.
const PHASE_LIST_MAX: usize = 30;
const PHASE_LIST_LONGEST: usize = 15;

/// Where the time went, by phase.
///
/// The rollup comes first because it is the answer most sessions want; the
/// ordered list is the narrative under it. Neither invents a name — every
/// label here is the mechanical one the facts carry.
fn phases_section(h: &mut String, s: &Summary) {
    if s.phases.is_empty() {
        return;
    }
    h.push_str("<section class=\"card\">\n<h2>Phases</h2>\n");
    h.push_str(&format!(
        "<p class=\"note\">{} phase(s), cut at every user turn and at every idle break. \
         A phase never spans a gap, and the phases in one stretch of work account for \
         all of it. Labels name the tool mix, not the intent.</p>\n",
        s.phases.len()
    ));

    let rollup = s.phase_rollup();
    let peak = rollup.first().map_or(1, |(_, _, secs)| (*secs).max(1));
    h.push_str("<ul class=\"bars\">\n");
    for (kind, n, secs) in &rollup {
        h.push_str(&format!(
            "<li><span class=\"name\">{}</span>\
             <span class=\"track\">\
             <span class=\"fill ph-{}\" style=\"width:{:.3}%\"></span>\
             </span><span class=\"n\">{} · {n} phase(s)</span></li>\n",
            esc(kind.label()),
            kind.label(),
            *secs as f64 * 100.0 / peak as f64,
            esc(&fmt::duration(*secs)),
        ));
    }
    h.push_str("</ul>\n");

    // Carry the index: a written label is keyed by position in the facts'
    // `phases`, and this list sorts and truncates.
    let mut shown: Vec<(usize, &Phase)> = s.phases.iter().enumerate().collect();
    let omitted = if shown.len() > PHASE_LIST_MAX {
        shown.sort_by(|a, b| b.1.secs.cmp(&a.1.secs).then(a.1.started.cmp(&b.1.started)));
        shown.truncate(PHASE_LIST_LONGEST);
        shown.sort_by_key(|(_, p)| p.started);
        s.phases.len() - PHASE_LIST_LONGEST
    } else {
        0
    };
    if omitted > 0 {
        h.push_str(&format!(
            "<p class=\"note\">Listing the {PHASE_LIST_LONGEST} longest; {omitted} shorter \
             phase(s) are not shown. The band on the strip above is the full sequence.</p>\n"
        ));
    }

    h.push_str("<ol class=\"turns phases\">\n");
    for (i, p) in shown {
        h.push_str(&format!(
            "<li class=\"ph-{}\"><span class=\"when\">{}</span><span class=\"what\">\
             <span class=\"chip kind\">{}</span> <strong>{}</strong>",
            p.kind.label(),
            esc(&clock(&p.started)),
            esc(p.kind.label()),
            esc(&fmt::duration(p.secs)),
        ));
        match &p.opened_by {
            Some(opened) => h.push_str(&format!(" — {}", esc(&label_of(opened)))),
            None => h.push_str(" — <em class=\"resumed\">resumed, nothing said</em>"),
        }
        // Beside the mechanical kind, never in place of it: `implementing` is
        // what the tool mix says, and the written label is what a model made
        // of it. Both, marked, or the reader cannot audit either.
        if let Some(written) = s.labels.as_ref().and_then(|l| l.phase(i)) {
            h.push_str(&format!(
                " <span class=\"chip said\">{}</span>",
                esc(written)
            ));
        }
        let mix = mix_line(p);
        if !mix.is_empty() {
            h.push_str(&format!("<br><span class=\"opts\">{}</span>", esc(&mix)));
        }
        h.push_str("</span></li>\n");
    }
    h.push_str("</ol>\n");

    let unbanded = phases_without_a_band(s);
    if unbanded > 0 {
        h.push_str(&format!(
            "<p class=\"note unknown\">{unbanded} phase(s) are shorter than one column at \
             this scale and carry no band on the strip. They are counted here — the strip \
             cannot draw them, which is not the same as their not existing.</p>\n"
        ));
    }
    h.push_str("</section>\n");
}

fn column(h: &mut String, b: &Bucket, peak: u32, at: &DateTime<Utc>, mark: Option<&Mark>) {
    let pct = if b.is_empty() {
        0
    } else {
        (6 + (b.records * 94).div_ceil(peak)).min(100)
    };
    let mut tip = format!("{} · {} record(s)", clock(at), b.records);
    if b.tool_calls > 0 {
        tip.push_str(&format!(", {} tool call(s)", b.tool_calls));
    }
    if b.tool_failures > 0 {
        tip.push_str(&format!(", {} failed", b.tool_failures));
    }
    if b.output_tokens > 0 {
        tip.push_str(&format!(", {} out", fmt::count(b.output_tokens)));
    }
    if let Some(m) = mark {
        tip.push_str(" — ");
        tip.push_str(&m.tip);
    }

    let class = if b.tool_failures > 0 {
        "bar fail"
    } else {
        "bar"
    };
    h.push_str(&format!("<div class=\"col-b\" title=\"{}\">", esc(&tip)));
    match mark {
        Some(m) => h.push_str(&format!("<i class=\"mk {}\"></i>", m.class)),
        None => h.push_str("<i class=\"mk\"></i>"),
    }
    h.push_str(&format!(
        "<div class=\"track\"><div class=\"{class}\" style=\"height:{pct}%\"></div></div></div>\n"
    ));
}

/// A user-involvement marker sitting over one bucket of the strip.
struct Mark {
    class: &'static str,
    tip: String,
}

/// Map each involvement moment onto the bucket that holds it.
///
/// A moment outside every span cannot happen — spans are built from the same
/// timestamps — but one without a timestamp is simply not placed.
fn marks_by_bucket(s: &Summary) -> BTreeMap<(usize, usize), Mark> {
    let mut out: BTreeMap<(usize, usize), Mark> = BTreeMap::new();
    let width = s.activity.bucket_secs.max(1);

    for item in &s.user_involvement {
        let Some(at) = item.at() else { continue };
        let Some((si, span)) = s
            .activity
            .spans
            .iter()
            .enumerate()
            .find(|(_, sp)| at >= sp.started && at <= sp.ended)
        else {
            continue;
        };
        let bi = (((at - span.started).num_seconds() / width) as usize).min(span.buckets.len() - 1);
        let (class, tip) = match item {
            Involvement::Prompt { preview, .. } => ("mkuser", label_of(preview)),
            Involvement::Question { question, .. } => ("mkask", format!("asked: {question}")),
        };
        out.entry((si, bi))
            .and_modify(|m| {
                m.tip.push_str(" / ");
                m.tip.push_str(&tip);
            })
            .or_insert(Mark { class, tip });
    }
    out
}

fn label_of(preview: &str) -> String {
    if preview.is_empty() {
        "user pasted an attachment".to_string()
    } else {
        preview.to_string()
    }
}

fn tool_mix(h: &mut String, s: &Summary) {
    h.push_str("<section class=\"card wide\">\n<h2>Tools</h2>\n");
    if s.tool_calls.is_empty() {
        h.push_str("<p class=\"note\">No tool calls in this session.</p>\n</section>\n");
        return;
    }
    let peak = s.tool_calls.values().copied().max().unwrap_or(1).max(1);
    let mut rows: Vec<(&String, &u32)> = s.tool_calls.iter().collect();
    rows.sort_by(|a, b| b.1.cmp(a.1).then_with(|| a.0.cmp(b.0)));

    h.push_str("<ul class=\"bars\">\n");
    for (name, n) in rows {
        let failed = s.tool_failures.get(name).copied().unwrap_or(0);
        let ok = n.saturating_sub(failed);
        h.push_str(&format!(
            "<li><span class=\"name\">{}</span>\
             <span class=\"track\">\
             <span class=\"fill\" style=\"width:{:.3}%\"></span>\
             <span class=\"fill fail\" style=\"width:{:.3}%\"></span>\
             </span><span class=\"n\">{n}{}</span></li>\n",
            esc(name),
            f64::from(ok) * 100.0 / f64::from(peak),
            f64::from(failed) * 100.0 / f64::from(peak),
            if failed > 0 {
                format!(" <em>{failed} failed</em>")
            } else {
                String::new()
            },
        ));
    }
    h.push_str("</ul>\n");

    let unknown = s.tool_failures.get("<unknown>").copied().unwrap_or(0);
    if unknown > 0 {
        h.push_str(&format!(
            "<p class=\"note\">{unknown} failure(s) could not be joined to a call — the \
             matching <code>tool_use</code> is not in this transcript.</p>\n"
        ));
    }
    h.push_str("</section>\n");
}

fn file_changes(h: &mut String, s: &Summary) {
    let c = &s.changes;
    h.push_str("<section class=\"card\">\n<h2>Files</h2>\n");
    h.push_str(&format!(
        "<p class=\"big\">{} file(s) <span class=\"add\">+{}</span> \
         <span class=\"del\">−{}</span></p>\n",
        c.files_touched,
        fmt::count(c.lines_added as u64),
        fmt::count(c.lines_deleted as u64),
    ));
    if !c.by_tool.is_empty() {
        // Where the numbers came from, so the reader can check the claim
        // rather than take it. Ordered by calls so the tool that did the most
        // is at the top, and the opaque ones cannot hide at the bottom.
        let mut rows: Vec<(&String, &crate::summary::ToolChanges)> = c.by_tool.iter().collect();
        rows.sort_by(|a, b| b.1.calls.cmp(&a.1.calls).then_with(|| a.0.cmp(b.0)));
        h.push_str("<ul class=\"sources\">\n");
        for (tool, t) in rows {
            let detail = if t.opaque == t.calls {
                "<span class=\"unseen\">no readable diff</span>".to_string()
            } else {
                format!(
                    "{} file(s) <span class=\"add\">+{}</span> <span class=\"del\">−{}</span>{}",
                    t.files_touched,
                    fmt::count(t.lines_added as u64),
                    fmt::count(t.lines_deleted as u64),
                    if t.opaque > 0 {
                        format!(" · <span class=\"unseen\">{} unreadable</span>", t.opaque)
                    } else {
                        String::new()
                    },
                )
            };
            h.push_str(&format!(
                "<li><span class=\"name\">{}</span><span class=\"n\">{}×</span>\
                 <span class=\"d\">{detail}</span></li>\n",
                esc(tool),
                t.calls,
            ));
        }
        h.push_str("</ul>\n");
    }
    if c.opaque_edits > 0 {
        h.push_str(&format!(
            "<p class=\"note unknown\">{} call(s) could have changed files and left no \
             recoverable diff. Those edits are <strong>not</strong> in the counts above — \
             an unknown, not a zero.</p>\n",
            c.opaque_edits
        ));
    }
    h.push_str("</section>\n");
}

