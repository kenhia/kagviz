/// Where the user was in the loop — the part a tool histogram cannot show.
fn involvement(h: &mut String, s: &Summary) {
    h.push_str("<section class=\"card\">\n<h2>User involvement</h2>\n");
    if s.user_involvement.is_empty() {
        h.push_str(
            "<p class=\"note\">The user did not speak after the opening prompt — this \
             session ran unattended.</p>\n</section>\n",
        );
        return;
    }
    h.push_str(&format!(
        "<p class=\"note\">{} prompt(s), {} question(s) asked, {} pasted \
         image(s)/document(s).</p>\n",
        s.user_prompts, s.ask_user_questions, s.pasted_attachments
    ));
    h.push_str("<ol class=\"turns\">\n");
    for item in &s.user_involvement {
        let when = item.at().map(|t| clock(&t)).unwrap_or_default();
        match item {
            Involvement::Prompt {
                preview,
                truncated,
                attachments,
                ..
            } => {
                h.push_str(&format!(
                    "<li class=\"prompt\"><span class=\"when\">{}</span>\
                     <span class=\"what\">{}{}{}</span></li>\n",
                    esc(&when),
                    esc(&label_of(preview)),
                    if *truncated { "…" } else { "" },
                    match attachments {
                        0 => String::new(),
                        n => format!(" <span class=\"chip\">+{n} attached</span>"),
                    },
                ));
            }
            Involvement::Question {
                header,
                question,
                options,
                chosen,
                ..
            } => {
                h.push_str(&format!(
                    "<li class=\"ask\"><span class=\"when\">{}</span><span class=\"what\">",
                    esc(&when)
                ));
                if let Some(head) = header {
                    h.push_str(&format!("<span class=\"chip\">{}</span> ", esc(head)));
                }
                h.push_str(&format!("{}<br>", esc(question)));
                match chosen {
                    Some(answer) => h.push_str(&format!(
                        "<span class=\"chose\">chose: {}</span>",
                        esc(answer)
                    )),
                    None => h.push_str("<span class=\"chose none\">no answer recorded</span>"),
                }
                if !options.is_empty() {
                    h.push_str(&format!(
                        " <span class=\"opts\">of {}</span>",
                        esc(&options.join(" · "))
                    ));
                }
                h.push_str("</span></li>\n");
            }
        }
    }
    h.push_str("</ol>\n</section>\n");
}

fn delegation(h: &mut String, s: &Summary) {
    if s.skills.is_empty() && s.subagents.is_empty() {
        // A sidecar can outlive the `Agent` record that spawned it, so the
        // tier is not gated on the chips above having anything to show.
        delegated_tier(h, s);
        return;
    }
    h.push_str("<section class=\"card\">\n<h2>Skills &amp; delegation</h2>\n<p>");
    for skill in &s.skills {
        h.push_str(&format!("<span class=\"chip\">/{}</span> ", esc(skill)));
    }
    for agent in &s.subagents {
        h.push_str(&format!(
            "<span class=\"chip agent\">{}</span> ",
            esc(agent)
        ));
    }
    h.push_str("</p>\n");
    h.push_str("</section>\n");
    delegated_tier(h, s);
}

/// Delegated work, as its own tier with an explicit combined line.
///
/// The tier is separate on purpose: rolling a subagent's 48 tool calls silently
/// into the parent's total would hide exactly the number a reader is here for,
/// and so would leaving them to add it up themselves. Both tiers, then the sum,
/// spelled out.
fn delegated_tier(h: &mut String, s: &Summary) {
    let d = &s.delegation;
    if d.is_empty() {
        return;
    }
    h.push_str("<section class=\"card wide\">\n<h2>Delegated work</h2>\n");

    if !d.spawns.is_empty() {
        h.push_str(
            "<table class=\"tier\">\n<thead><tr><th>agent</th><th>what for</th>\
                    <th class=\"r\">tools</th><th class=\"r\">active</th>\
                    <th class=\"r\">output</th></tr></thead>\n<tbody>\n",
        );
        for spawn in &d.spawns {
            let calls: u32 = spawn.tool_calls.values().sum();
            let failed: u32 = spawn.tool_failures.values().sum();
            h.push_str(&format!(
                "<tr><td><span class=\"chip agent\">{}</span>{}</td><td>{}</td>\
                 <td class=\"r\">{calls}{}</td><td class=\"r\">{}</td>\
                 <td class=\"r\">{}</td></tr>\n",
                esc(spawn.subagent_type.as_deref().unwrap_or("agent")),
                spawn
                    .model
                    .as_deref()
                    .map(|m| format!("<span class=\"sub\">{}</span>", esc(m)))
                    .unwrap_or_default(),
                esc(spawn.description.as_deref().unwrap_or("—")),
                if failed > 0 {
                    format!(" <em>{failed} failed</em>")
                } else {
                    String::new()
                },
                fmt::duration(spawn.active_secs),
                fmt::count(spawn.tokens.output),
            ));
        }
        h.push_str("</tbody>\n</table>\n");
    }

    let delegated_calls: u32 = d.totals.tool_calls.values().sum();
    h.push_str(&format!(
        "<p class=\"combined\">Session <strong>{}</strong> tool call(s) · delegated \
         <strong>{delegated_calls}</strong> · <strong>{}</strong> combined. \
         Output tokens {} + {} = <strong>{}</strong>.</p>\n",
        s.total_tool_calls(),
        s.combined_tool_calls(),
        fmt::count(s.tokens.output),
        fmt::count(d.totals.tokens.output),
        fmt::count(s.combined_output_tokens()),
    ));
    // Seconds are the one thing that does not add: a subagent runs while the
    // parent waits on it, so the two overlap in real time. Said out loud,
    // because a table of per-agent "active" invites the sum.
    h.push_str(
        "<p class=\"note\">Active time is <strong>not</strong> summed: a subagent runs \
         while the session waits on it, so those seconds overlap rather than add.</p>\n",
    );

    if d.unjoined_spawns > 0 {
        h.push_str(&format!(
            "<p class=\"note unknown\">{} spawn(s) left no transcript to read. Their work \
             happened and is <strong>not</strong> in any number here — an unknown, not a \
             zero.</p>\n",
            d.unjoined_spawns
        ));
    }
    if d.inline_records > 0 {
        h.push_str(&format!(
            "<p class=\"note\">{} record(s) in this transcript were subagent turns inlined \
             by an older CLI. They are counted in this tier, not in the session's own \
             totals.</p>\n",
            d.inline_records
        ));
    }
    h.push_str("</section>\n");
}

fn meta(h: &mut String, key: &str, value: impl AsRef<str>) {
    let value = value.as_ref();
    if value.is_empty() {
        return;
    }
    h.push_str(&format!(
        "<dt>{}</dt><dd>{}</dd>\n",
        esc(key),
        esc(value.trim())
    ));
}

fn stat(h: &mut String, key: &str, value: &str, note: &str) {
    h.push_str(&format!(
        "<div class=\"stat\"><span class=\"k\">{}</span><span class=\"v\">{}</span>\
         <span class=\"n\">{}</span></div>\n",
        esc(key),
        esc(value),
        esc(note)
    ));
}

fn join(items: impl Iterator<Item = String>) -> String {
    items.collect::<Vec<_>>().join(", ")
}

fn stamp(t: &DateTime<Utc>) -> String {
    t.to_rfc3339_opts(SecondsFormat::Secs, true)
}

fn clock(t: &DateTime<Utc>) -> String {
    t.format("%m-%d %H:%M:%S").to_string()
}

/// Escape for both element text and double-quoted attributes.
///
/// Tool output and prompt text go straight onto the page, and both routinely
/// contain angle brackets and quotes.
pub(crate) fn esc(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for c in raw.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

